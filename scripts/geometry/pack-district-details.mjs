// Derive individual exact TopoJSON forms and per-year adjacency from existing assets.
// No rounding, simplification or cross-period identity inference.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
const directory = 'public/data/geometry';
const catalog = readFileSync('src/utils/electoralTopologyAsset.ts', 'utf8');
const paths = JSON.parse(catalog.match(/= (\{[\s\S]*?\});/)[1]);
const hash = data => createHash('sha256').update(data).digest('hex');
const seen = new Set();
const detailPaths = {};
const summary = [];
let previous;
function write(prefix, extension, value) {
  const data = JSON.stringify(value);
  const path = `/data/geometry/${prefix}-${hash(data)}.${extension}`;
  writeFileSync(`public${path}`, data);
  writeFileSync(`public${path}.gz`, gzipSync(data, { level: 9 }));
  return path;
}
for (const [year, path] of Object.entries(paths)) {
  const manifest = JSON.parse(readFileSync(`public${path}`, 'utf8'));
  const packages = new Map();
  const edges = new Map();
  const neighbors = new Map(manifest.districts.map(d => [Number(d.properties.Nummer), new Set()]));
  for (const district of manifest.districts) {
    if (!packages.has(district.package)) packages.set(district.package, JSON.parse(readFileSync(`public${district.package}`, 'utf8')));
    const source = packages.get(district.package);
    const geometry = source.objects[district.shape].geometries[0];
    const arcs = [];
    const index = new Map();
    const number = Number(district.properties.Nummer);
    const remap = refs => Array.isArray(refs) ? refs.map(remap) : (() => {
      const id = refs < 0 ? ~refs : refs;
      if (!index.has(id)) { index.set(id, arcs.length); arcs.push(source.arcs[id]); }
      return refs < 0 ? ~index.get(id) : index.get(id);
    })();
    const topology = { type: 'Topology', objects: { [district.shape]: { type: 'GeometryCollection', geometries: [{ ...geometry, arcs: remap(geometry.arcs) }] } }, arcs };
    // Shared line segments define adjacency; point contacts alone do not.
    for (const points of arcs) for (let i = 1; i < points.length; i++) {
      const a = JSON.stringify(points[i - 1]), b = JSON.stringify(points[i]);
      if (a === b) continue;
      const key = a < b ? `${a}|${b}` : `${b}|${a}`;
      const owners = edges.get(key) ?? [];
      for (const owner of owners) if (owner !== number) { neighbors.get(number).add(owner); neighbors.get(owner).add(number); }
      if (!owners.includes(number)) owners.push(number);
      edges.set(key, owners);
    }
    const singlePath = `/data/geometry/district-${district.shape}.topojson`;
    if (!seen.has(district.shape)) {
      const data = JSON.stringify(topology);
      writeFileSync(`public${singlePath}`, data);
      writeFileSync(`public${singlePath}.gz`, gzipSync(data, { level: 9 }));
      seen.add(district.shape);
    }
    district.package = singlePath;
  }
  for (const district of manifest.districts) district.neighbors = [...neighbors.get(Number(district.properties.Nummer))].sort((a, b) => a - b);
  detailPaths[year] = write(`district-manifest-${year}`, 'json', manifest);
  const priorForms = new Set(previous?.districts.map(d => d.shape));
  summary.push({ year: Number(year), districts: manifest.districts.length, reusedExactFormsFromPreviousBoundary: previous ? manifest.districts.filter(d => priorForms.has(d.shape)).length : null });
  previous = manifest;
  console.log(`Prepared ${year}: ${manifest.districts.length} districts`);
}
writeFileSync('src/utils/electoralDistrictAsset.ts', `// Generated by scripts/geometry/pack-district-details.mjs\nexport const ELECTORAL_DISTRICT_MANIFESTS: Readonly<Record<number, string>> = ${JSON.stringify(detailPaths, null, 2)};\n`);
writeFileSync(`${directory}/district-comparison.json`, JSON.stringify({ uniqueExactForms: seen.size, boundaryVersions: summary }, null, 2));
console.log(`Stored ${seen.size} unique exact forms`);
