// No rounding, quantization or simplification: only exact arc deduplication.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
const inputs = process.argv.slice(2);
if (inputs.length !== 2) throw new Error('Usage: node scripts/geometry/pack-election-topology.mjs 2016.topojson 2021.topojson');
const topology = { type: 'Topology', objects: {}, arcs: [] };
const index = new Map();
for (const [i, file] of inputs.entries()) {
  const source = JSON.parse(readFileSync(file, 'utf8'));
  if (source.type !== 'Topology' || source.transform) throw new Error('Expected unquantized Topology');
  const remap = source.arcs.map(arc => {
    const key = JSON.stringify(arc);
    if (index.has(key)) return index.get(key);
    const id = topology.arcs.length;
    topology.arcs.push(arc);
    index.set(key, id);
    const reverse = JSON.stringify([...arc].reverse());
    if (!index.has(reverse)) index.set(reverse, ~id);
    return id;
  });
  const mapArcs = value => Array.isArray(value) ? value.map(mapArcs) : value < 0 ? ~remap[~value] : remap[value];
  const mapGeometry = geometry => ({ ...geometry,
    ...(geometry.arcs ? { arcs: mapArcs(geometry.arcs) } : {}),
    ...(geometry.geometries ? { geometries: geometry.geometries.map(mapGeometry) } : {}),
  });
  const objects = Object.values(source.objects);
  if (objects.length !== 1) throw new Error('Expected one district object');
  topology.objects[`year${i === 0 ? 2016 : 2021}`] = mapGeometry(objects[0]);
}
const data = Buffer.from(JSON.stringify(topology));
const hash = createHash('sha256').update(data).digest('hex');
const basename = `bw-landtag-${hash}.topojson`;
mkdirSync('public/data/geometry', { recursive: true });
writeFileSync(`public/data/geometry/${basename}`, data);
const gzip = gzipSync(data, { level: 9 });
const brotli = brotliCompressSync(data, { params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_MODE]: constants.BROTLI_MODE_TEXT } });
writeFileSync(`public/data/geometry/${basename}.gz`, gzip);
writeFileSync(`public/data/geometry/${basename}.br`, brotli);
writeFileSync('src/utils/electoralTopologyAsset.ts', `// Generated by scripts/geometry/pack-election-topology.mjs\nexport const ELECTORAL_TOPOLOGY_ASSET = "/data/geometry/${basename}";\n`);
console.log(JSON.stringify({ hash, arcs: topology.arcs.length, bytes: data.length, gzip: gzip.length, brotli: brotli.length }));
