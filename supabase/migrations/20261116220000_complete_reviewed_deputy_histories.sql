END $$;

-- Use one trigger and one lock convention for future imports. A known person's
-- history also survives a party change. Ambiguous names remain separate.
DROP TRIGGER IF EXISTS b_election_history_connect_matching ON public.election_history_mandates;
CREATE OR REPLACE FUNCTION public.assign_election_mandate_connection() RETURNS trigger
LANGUAGE plpgsql SET search_path=public AS $$
DECLARE display_name text; targets uuid[];
BEGIN
 IF NEW.connection_id IS NOT NULL THEN RETURN NEW; END IF;
 display_name:=lower(regexp_replace(btrim(coalesce(nullif(btrim(NEW.person_name),''),
   (SELECT p.name FROM public.election_history_people p WHERE p.id=NEW.person_id))),'[[:space:]]+',' ','g'));
 IF nullif(display_name,'') IS NULL THEN
   NEW.connection_id:=gen_random_uuid(); RETURN NEW;
 END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(display_name,0));
 -- Confirmed identities take precedence over a display name.
 IF NEW.person_id IS NOT NULL THEN
   SELECT array_agg(DISTINCT m.connection_id) INTO targets
   FROM public.election_history_mandates m
   WHERE m.id<>NEW.id AND m.person_id=NEW.person_id AND m.connection_id IS NOT NULL;
 END IF;
 IF coalesce(cardinality(targets),0)=0 THEN
   SELECT array_agg(DISTINCT m.connection_id) INTO targets
   FROM public.election_history_mandates m LEFT JOIN public.election_history_people p ON p.id=m.person_id
   WHERE m.id<>NEW.id AND m.connection_id IS NOT NULL
     AND lower(regexp_replace(btrim(coalesce(nullif(btrim(m.person_name),''),p.name)),'[[:space:]]+',' ','g'))=display_name;
   -- Count ALL matching histories before filtering. Excluding a same-period
   -- homonym first could incorrectly select the other person's history.
   IF cardinality(targets)=1 AND EXISTS (
     SELECT 1 FROM public.election_history_mandates member
     WHERE member.connection_id=targets[1] AND member.id<>NEW.id
       AND (member.period_id=NEW.period_id OR
         (NEW.person_id IS NOT NULL AND member.person_id IS NOT NULL AND member.person_id<>NEW.person_id))
   ) THEN targets:=NULL; END IF;
 END IF;
 NEW.connection_id:=CASE WHEN cardinality(targets)=1 THEN targets[1] ELSE gen_random_uuid() END;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS election_history_assign_connection ON public.election_history_mandates;
CREATE TRIGGER election_history_assign_connection
BEFORE INSERT OR UPDATE OF person_name,person_id,party,party_label
ON public.election_history_mandates
FOR EACH ROW EXECUTE FUNCTION public.assign_election_mandate_connection();
COMMIT;
